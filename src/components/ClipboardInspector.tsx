import React, { useState } from 'react';
import {
  Copy,
  Check,
  Code,
  FileText,
  ClipboardPaste,
  ShieldCheck,
  Info,
} from 'lucide-react';
import type { BlocopySession, ToastMessage } from '../core/blocopy-controller.js';

interface ClipboardInspectorProps {
  session: BlocopySession | null;
  addToast: (toast: Omit<ToastMessage, 'id'>) => void;
}

export const ClipboardInspector: React.FC<ClipboardInspectorProps> = ({ session, addToast }) => {
  const [activeFormat, setActiveFormat] = useState<'preview' | 'html' | 'text'>('preview');
  const [copiedState, setCopiedState] = useState<string | null>(null);
  const [pasteContent, setPasteContent] = useState<string>('');

  const payload = session?.payload;

  const handleCopyCode = async (text: string, label: string) => {
    try {
      await navigator.clipboard.writeText(text);
      setCopiedState(label);
      setTimeout(() => setCopiedState(null), 2000);
      addToast({
        type: 'copied',
        message: `Copied ${label} to clipboard`,
      });
    } catch {
      addToast({
        type: 'warn',
        message: 'Could not copy to clipboard',
      });
    }
  };

  const handleSimulatePaste = async () => {
    try {
      if (typeof navigator.clipboard.readText === 'function') {
        const text = await navigator.clipboard.readText();
        setPasteContent(text);
        addToast({
          type: 'info',
          message: 'Pasted content from clipboard into verification box',
        });
      } else if (payload?.text) {
        setPasteContent(payload.text);
        addToast({
          type: 'info',
          message: 'Loaded active payload into verification box',
        });
      }
    } catch {
      if (payload?.text) {
        setPasteContent(payload.text);
      }
    }
  };

  const characterCount = payload?.text.length ?? 0;
  const wordCount = payload?.text ? payload.text.trim().split(/\s+/).filter(Boolean).length : 0;

  return (
    <div className="space-y-6">
      {/* Overview Card */}
      <div className="bg-white rounded-2xl border border-slate-200 p-6 shadow-xs">
        <div className="flex flex-wrap items-center justify-between gap-4 border-b border-slate-100 pb-5">
          <div>
            <h2 className="text-xl font-bold text-slate-900 tracking-tight flex items-center gap-2">
              <ClipboardPaste className="w-5 h-5 text-blue-600" />
              <span>Real-time Clipboard Inspector</span>
            </h2>
            <p className="text-xs text-slate-500 mt-1">
              Dual-format output generated by Blocopy's strict DOM sanitizer and plaintext engine
            </p>
          </div>

          {payload && (
            <div className="flex items-center gap-2">
              <button
                type="button"
                onClick={() => handleCopyCode(payload.text, 'Plain Text')}
                className="inline-flex items-center gap-1.5 px-3 py-1.5 text-xs font-semibold rounded-lg bg-slate-100 hover:bg-slate-200 text-slate-700 transition-colors"
              >
                {copiedState === 'Plain Text' ? (
                  <Check className="w-3.5 h-3.5 text-emerald-600" />
                ) : (
                  <Copy className="w-3.5 h-3.5" />
                )}
                <span>Copy Plain Text</span>
              </button>

              <button
                type="button"
                onClick={() => handleCopyCode(payload.html, 'Clean HTML')}
                className="inline-flex items-center gap-1.5 px-3 py-1.5 text-xs font-semibold rounded-lg bg-blue-600 hover:bg-blue-700 text-white shadow-xs transition-colors"
              >
                {copiedState === 'Clean HTML' ? (
                  <Check className="w-3.5 h-3.5" />
                ) : (
                  <Copy className="w-3.5 h-3.5" />
                )}
                <span>Copy HTML</span>
              </button>
            </div>
          )}
        </div>

        {/* Quick Stats Grid */}
        <div className="grid grid-cols-2 sm:grid-cols-4 gap-3 mt-4">
          <div className="bg-slate-50 p-3 rounded-xl border border-slate-100">
            <span className="text-[11px] font-semibold text-slate-500 uppercase tracking-wider block">
              Words
            </span>
            <span className="text-xl font-bold text-slate-900">{wordCount}</span>
          </div>

          <div className="bg-slate-50 p-3 rounded-xl border border-slate-100">
            <span className="text-[11px] font-semibold text-slate-500 uppercase tracking-wider block">
              Characters
            </span>
            <span className="text-xl font-bold text-slate-900">{characterCount}</span>
          </div>

          <div className="bg-slate-50 p-3 rounded-xl border border-slate-100">
            <span className="text-[11px] font-semibold text-slate-500 uppercase tracking-wider block">
              Units Kept
            </span>
            <span className="text-xl font-bold text-emerald-600">
              {session?.includedUnits.length || 0}
            </span>
          </div>

          <div className="bg-slate-50 p-3 rounded-xl border border-slate-100">
            <span className="text-[11px] font-semibold text-slate-500 uppercase tracking-wider block">
              Excluded Units
            </span>
            <span className="text-xl font-bold text-rose-500">
              {session?.excludedUnits.length || 0}
            </span>
          </div>
        </div>
      </div>

      {/* Main Payload Viewer & Tabs */}
      <div className="bg-white rounded-2xl border border-slate-200 overflow-hidden shadow-xs">
        {/* Tab Headers */}
        <div className="flex items-center justify-between border-b border-slate-200 bg-slate-50/70 px-4 py-2">
          <div className="flex items-center gap-1">
            <button
              type="button"
              onClick={() => setActiveFormat('preview')}
              className={`px-3 py-1.5 rounded-lg text-xs font-semibold flex items-center gap-1.5 transition-all ${
                activeFormat === 'preview'
                  ? 'bg-white text-blue-600 shadow-xs'
                  : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              <FileText className="w-3.5 h-3.5" />
              <span>HTML Render Preview</span>
            </button>

            <button
              type="button"
              onClick={() => setActiveFormat('html')}
              className={`px-3 py-1.5 rounded-lg text-xs font-semibold flex items-center gap-1.5 transition-all ${
                activeFormat === 'html'
                  ? 'bg-white text-blue-600 shadow-xs'
                  : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              <Code className="w-3.5 h-3.5" />
              <span>Sanitized HTML Code</span>
            </button>

            <button
              type="button"
              onClick={() => setActiveFormat('text')}
              className={`px-3 py-1.5 rounded-lg text-xs font-semibold flex items-center gap-1.5 transition-all ${
                activeFormat === 'text'
                  ? 'bg-white text-blue-600 shadow-xs'
                  : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              <FileText className="w-3.5 h-3.5" />
              <span>Structured Plain Text</span>
            </button>
          </div>

          <span className="text-[11px] text-slate-500 font-mono">
            {activeFormat === 'preview' && 'text/html (formatted)'}
            {activeFormat === 'html' && 'text/html (source)'}
            {activeFormat === 'text' && 'text/plain (UTF-8)'}
          </span>
        </div>

        {/* Tab Contents */}
        <div className="p-6">
          {!payload ? (
            <div className="py-16 text-center space-y-3">
              <div className="w-12 h-12 mx-auto rounded-2xl bg-blue-50 text-blue-600 flex items-center justify-center">
                <Info className="w-6 h-6" />
              </div>
              <h3 className="text-base font-semibold text-slate-800">
                No Active Clipboard Selection
              </h3>
              <p className="text-xs text-slate-500 max-w-md mx-auto">
                Double-click any paragraph or message in the Interactive Document tab. Blocopy will
                instantly compile and display the sanitized HTML and markdown plain text here.
              </p>
            </div>
          ) : (
            <>
              {activeFormat === 'preview' && (
                <div className="space-y-4">
                  <div className="p-3 bg-emerald-50 border border-emerald-200 rounded-lg text-xs text-emerald-800 flex items-center gap-2">
                    <ShieldCheck className="w-4 h-4 text-emerald-600 shrink-0" />
                    <span>
                      This is how rich applications (Google Docs, Microsoft Word, Notion, Slack) render
                      the pasted HTML payload.
                    </span>
                  </div>
                  <div
                    className="p-6 bg-slate-50/60 rounded-xl border border-slate-200 prose max-w-none text-slate-800"
                    dangerouslySetInnerHTML={{ __html: payload.html }}
                  />
                </div>
              )}

              {activeFormat === 'html' && (
                <div className="space-y-3">
                  <div className="flex items-center justify-between text-xs text-slate-500">
                    <span>
                      Allowlisted tags only: headings, p, ul, ol, li, blockquote, pre, code, strong,
                      em, a (clean URLs).
                    </span>
                    <button
                      type="button"
                      onClick={() => handleCopyCode(payload.html, 'HTML Code')}
                      className="text-blue-600 hover:text-blue-800 font-medium"
                    >
                      Copy code
                    </button>
                  </div>
                  <pre className="p-4 bg-slate-900 text-slate-100 rounded-xl text-xs font-mono overflow-x-auto leading-relaxed max-h-96">
                    <code>{payload.html}</code>
                  </pre>
                </div>
              )}

              {activeFormat === 'text' && (
                <div className="space-y-3">
                  <div className="flex items-center justify-between text-xs text-slate-500">
                    <span>
                      Normalized markdown plaintext: list bullets (<code>-</code>, <code>1.</code>),
                      quotes (<code>&gt;</code>), preserved paragraphs.
                    </span>
                    <button
                      type="button"
                      onClick={() => handleCopyCode(payload.text, 'Plain Text')}
                      className="text-blue-600 hover:text-blue-800 font-medium"
                    >
                      Copy plaintext
                    </button>
                  </div>
                  <pre className="p-4 bg-slate-900 text-slate-100 rounded-xl text-xs font-mono overflow-x-auto leading-relaxed max-h-96 whitespace-pre-wrap">
                    <code>{payload.text}</code>
                  </pre>
                </div>
              )}
            </>
          )}
        </div>
      </div>

      {/* Paste Verification Sandbox */}
      <div className="bg-white rounded-2xl border border-slate-200 p-6 shadow-xs space-y-4">
        <div className="flex flex-wrap items-center justify-between gap-3">
          <div>
            <h3 className="text-base font-bold text-slate-900 flex items-center gap-2">
              <ClipboardPaste className="w-4 h-4 text-indigo-600" />
              <span>Paste Verification Zone</span>
            </h3>
            <p className="text-xs text-slate-500 mt-0.5">
              Press <kbd className="px-1.5 py-0.5 bg-slate-100 border border-slate-300 rounded text-[10px] font-mono">Ctrl+V</kbd> or <kbd className="px-1.5 py-0.5 bg-slate-100 border border-slate-300 rounded text-[10px] font-mono">Cmd+V</kbd> below to test what lands on your clipboard.
            </p>
          </div>

          <div className="flex items-center gap-2">
            <button
              type="button"
              onClick={handleSimulatePaste}
              className="px-3 py-1.5 text-xs font-semibold rounded-lg bg-indigo-50 text-indigo-700 hover:bg-indigo-100 border border-indigo-200 transition-colors"
            >
              Paste from Clipboard
            </button>
            {pasteContent && (
              <button
                type="button"
                onClick={() => setPasteContent('')}
                className="px-2.5 py-1.5 text-xs font-medium rounded-lg text-slate-500 hover:text-slate-800 hover:bg-slate-100 transition-colors"
              >
                Clear
              </button>
            )}
          </div>
        </div>

        <div
          contentEditable
          suppressContentEditableWarning
          onInput={(e) => setPasteContent(e.currentTarget.innerText)}
          data-placeholder="Click here and press Ctrl+V (or Cmd+V) to test pasting..."
          className="w-full min-h-[110px] p-4 bg-slate-50/80 rounded-xl border border-dashed border-slate-300 focus:outline-hidden focus:border-indigo-500 focus:ring-2 focus:ring-indigo-100 text-sm text-slate-800 transition-all font-sans"
        >
          {pasteContent}
        </div>
      </div>
    </div>
  );
};
